package org.testleaf.week1.day2;

public class LearnForLoops {

    public static void main(String[] args) {
        
        //print the numbers for 1 to 5
         for(int i=1;i<5;i++){
          System.out.println(i);
         }

         System.out.println("-----------------------------");

         //print the numbers from 5 to 1
        for(int i=5;i>=1;i--){
         System.out.println(i);
         }
    }
}
